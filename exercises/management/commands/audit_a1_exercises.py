"""Report exercise questions that cannot teach anything.

    python manage.py audit_a1_exercises

Read-only: it runs SELECT queries and writes nothing. It always exits 0 unless
``--strict`` is given, because it is a report about content quality rather than a
gate the content must pass.

Why this exists
---------------
The exercise content is written by hand in ``exercises/data/a1_exercises.json`` and
generated by the ``seed_a1_*`` commands. Two kinds of mistake kept turning up by hand,
each of them a question that asks nothing:

* **the answer is already on the page** — the prompt names the very thing it asks
  about. ``جایگزین _____ در جمله زیر شود: „Auf Wiedersehen!“`` whose answer is
  ``auf Wiedersehen`` is not a question; the learner copies the sentence.
* **the blank is not there** — a FILL_BLANK prompt that never shows where the word
  should go, so the answer cannot be derived from anything.

Both were found by reading pages, which does not scale. This command turns that
reading into a repeatable check: it walks every question and its answers and reports
the ones that break a rule, with the exercise and the prompt so each can be traced to
its source and fixed there.

The checks
----------
``no_answers``          a question with no Answer rows at all — nothing can be graded.
``no_correct_answer``   answers exist but none is marked correct.
``empty_text``          a blank prompt, or a blank option.
``duplicate_options``   two options of one question that say the same thing.
``prompt_is_answer``    the whole prompt is the correct answer.
``answer_in_prompt``    the correct answer appears as a whole word/phrase inside the
                        prompt, so the learner can read it off.
``blank_missing``       a FILL_BLANK prompt whose quoted sentence has no ``___`` marker
                        in it, so the learner is never shown where the word goes.
``duplicate_question``  two questions of one exercise that ask the same thing.

Matching folds whitespace and case but not words, and it matches on whole-word
boundaries, so ``es`` is not reported inside ``dieses``. The one shape it cannot catch
is a translation: an answer that is the meaning of a word the prompt names is a real
question, not a leak, so the check compares like forms — a German answer against a
German prompt, a Persian answer against a Persian prompt — and skips a pair that is
written in two scripts, because those are not the same string by accident.
"""

import re

from django.core.management.base import BaseCommand, CommandError

from lessons.models import LanguageLevel
from exercises.models import Exercise, Question

#: A FILL_BLANK prompt has to show where the word goes, and the blank has to be inside
#: the sentence being filled, not only in the instruction above it. The authored and
#: generated prompts both use a run of underscores; ``…`` is accepted too, so a later
#: authoring style is not reported as missing a blank.
BLANK_MARKERS = ("___", "…")

#: The character that opens and closes the German sentence of a FILL_BLANK prompt. The
#: sentence is the quoted part; the instruction around it may mention a blank without
#: ever showing one where the word should go.
QUOTE = '"'

#: How much of a prompt to print beside a problem. A prompt can be a whole passage.
PROMPT_LIMIT = 90

#: Latin and Persian are written in different scripts, so a German answer and a Persian
#: prompt cannot be the same string by accident. Comparing them would report every
#: translation question as a leak, so a mismatched pair is skipped.
LATIN = re.compile(r"[A-Za-z]")
PERSIAN = re.compile(r"[\u0600-\u06FF]")


def canonical(text):
    """One comparable form of a prompt or an answer: whitespace folded, lower case.

    Punctuation is kept on purpose. The comparison looks for a whole word or phrase
    inside another string, and a trailing ``!`` is not part of the word — keeping it
    means ``Guten Morgen!`` is still found inside ``... „Guten Morgen!“ ...``.
    """
    return " ".join(str(text).split()).lower()


def same_script(one, other):
    """Whether two strings are written in the same script, Latin or Persian.

    A pair with one of each is a translation and is never a leak, so it is left alone.
    A string with no letters at all (a number, an id) is compared as usual.
    """
    one_latin = bool(LATIN.search(one))
    other_latin = bool(LATIN.search(other))

    if one_latin and not other_latin:
        return False
    if other_latin and not one_latin:
        return False

    return True


def contains_phrase(haystack, needle):
    """Whether ``needle`` appears inside ``haystack`` as a whole word or phrase.

    Both are already canonical. Whitespace between the needle's words matches any run
    of whitespace, and the edges require a non-word character (or an edge), so ``es``
    does not match inside ``dieses``.
    """
    tokens = needle.split()
    if not tokens:
        return False

    pattern = r"(?<!\w)" + r"\s+".join(re.escape(token) for token in tokens) + r"(?!\w)"
    return re.search(pattern, haystack) is not None


class Command(BaseCommand):
    help = "Report exercise questions that cannot teach anything (answer leakage, missing blanks, duplicates)."

    def add_arguments(self, parser):
        parser.add_argument("--level", default="A1", help="Language level code (default A1).")
        parser.add_argument(
            "--show", type=int, default=12, help="How many examples to print per problem."
        )
        parser.add_argument(
            "--all", action="store_true", help="Print every problem, not just --show of them."
        )
        parser.add_argument(
            "--strict",
            action="store_true",
            help="Exit 1 when any problem is found. Off by default: this is a report.",
        )

    def level_exercises(self, level):
        """Every exercise of the level, with its questions and answers loaded."""
        return (
            Exercise.objects.filter(lesson__course__language_level=level)
            .select_related("lesson")
            .prefetch_related("questions__answers")
            .order_by("lesson__order", "order", "pk")
        )

    def question_problems(self, question):
        """The problems one question has, as ``(name, detail)`` pairs.

        Returns at least one row only when something is wrong; a healthy question
        returns an empty list.
        """
        problems = []
        answers = list(question.answers.all())

        if not answers:
            problems.append(("no_answers", "question has no answers"))
            return problems

        correct = [answer for answer in answers if answer.is_correct]
        if not correct:
            problems.append(("no_correct_answer", "no option is marked correct"))

        prompt = canonical(question.prompt)
        if not prompt:
            problems.append(("empty_text", "empty prompt"))

        seen = []
        for answer in answers:
            text = canonical(answer.text)
            if not text:
                problems.append(("empty_text", f"empty option text (order {answer.order})"))
            if text in seen:
                problems.append(("duplicate_options", f"duplicate option: {answer.text!r}"))
            else:
                seen.append(text)

        correct_text = canonical(correct[0].text) if correct else ""

        if correct_text and prompt and correct_text == prompt:
            problems.append(("prompt_is_answer", f"prompt is the answer: {correct_text!r}"))

        if correct_text and prompt and same_script(prompt, correct_text):
            if contains_phrase(prompt, correct_text):
                problems.append(
                    ("answer_in_prompt", f"answer {correct_text!r} is inside the prompt")
                )

        if question.exercise.type == Exercise.ExerciseType.FILL_BLANK:
            # Only the quoted sentence matters: a blank in the instruction does not tell
            # the learner where the word goes.
            first = question.prompt.find(QUOTE)
            last = question.prompt.rfind(QUOTE)
            if first != -1 and last > first:
                sentence = question.prompt[first + 1 : last]
            else:
                sentence = question.prompt

            has_blank = False
            for marker in BLANK_MARKERS:
                if marker in sentence:
                    has_blank = True
                    break
            if not has_blank:
                problems.append(
                    ("blank_missing", f"FILL_BLANK sentence has no ___ marker: {sentence!r}")
                )

        return problems

    def exercise_duplicates(self, exercise):
        """The questions of one exercise that ask the same thing, as ``(name, detail)``.

        Two questions are the same when their prompt, their option texts **and** which one
        is correct all match — the same words asked twice with the same choices and the
        same answer is repetition with no educational difference. Asking the two halves of
        a minimal pair (``kochen`` against ``Kuchen``, then ``Kuchen`` against ``kochen``)
        has the same prompt and the same options but a different correct answer, and it is
        a real pair of questions rather than a duplicate, so the verdict is part of the
        fingerprint.

        The shared instruction of a drill (``به فایل گوش کن و …``) is not a question: it
        repeats because each audio question carries it. Only questions whose prompt is
        not the same as the exercise's instruction are compared, so that whole drill does
        not look like one question asked a hundred times.
        """
        problems = []
        instruction = canonical(exercise.instruction)
        seen = {}

        for question in exercise.questions.all():
            prompt = canonical(question.prompt)
            if not prompt or prompt == instruction:
                continue

            options = []
            correct = ""
            for answer in question.answers.all():
                options.append(canonical(answer.text))
                if answer.is_correct and not correct:
                    correct = canonical(answer.text)
            options.sort()

            fingerprint = prompt + " || " + " | ".join(options) + " || " + correct

            if fingerprint in seen:
                problems.append(
                    ("duplicate_question", f"asked again in question {seen[fingerprint]}: {prompt[:PROMPT_LIMIT]}")
                )
            else:
                seen[fingerprint] = question.order

        return problems

    def print_problems(self, name, rows, show, show_all):
        """One section of the report: the rule, its count, and some examples."""
        if not rows:
            self.stdout.write(self.style.SUCCESS(f"  ok    {name}"))
            return 0

        self.stdout.write(self.style.WARNING(f"  found {name} ({len(rows)} question(s))"))
        shown = rows
        if not show_all:
            shown = rows[:show]
        for detail in shown:
            self.stdout.write(f"          {detail}")
        if len(shown) < len(rows):
            self.stdout.write(f"          … and {len(rows) - len(shown)} more (use --all)")
        return len(rows)

    def handle(self, *args, **options):
        code = options["level"]
        level = LanguageLevel.objects.filter(level=code).first()
        if level is None:
            raise CommandError(f"LanguageLevel {code!r} does not exist.")

        show = options["show"]
        show_all = options["all"]

        # Every problem, by check name, as printed rows.
        collected = {
            "no_answers": [],
            "no_correct_answer": [],
            "empty_text": [],
            "duplicate_options": [],
            "prompt_is_answer": [],
            "answer_in_prompt": [],
            "blank_missing": [],
            "duplicate_question": [],
        }

        exercises = list(self.level_exercises(level))
        question_total = 0

        for exercise in exercises:
            for question in exercise.questions.all():
                question_total += 1
                for name, detail in self.question_problems(question):
                    collected[name].append(
                        f"[{exercise.title} · سؤال {question.order}] {detail} :: {question.prompt[:PROMPT_LIMIT]!r}"
                    )

            for name, detail in self.exercise_duplicates(exercise):
                collected[name].append(f"[{exercise.title}] {detail}")

        self.stdout.write(
            f"Audited {len(exercises)} exercises · {question_total} questions "
            f"({code}, all exercises including drafts)"
        )
        self.stdout.write("")

        failed = 0
        for name in collected:
            failed += self.print_problems(name, collected[name], show, show_all)

        self.stdout.write("")
        if failed:
            self.stdout.write(
                self.style.WARNING(
                    f"{failed} problem(s) found. This is a report — exit code is 0 unless --strict."
                )
            )
            if options["strict"]:
                raise CommandError(f"{failed} content problem(s) found.")
        else:
            self.stdout.write(self.style.SUCCESS("No content problems found."))
